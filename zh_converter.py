# 构建字映射字典
_T2S_TABLE = {ord(t): ord(s) for t, s in zip(_TRAD_CHARS, _SIMP_CHARS)}
_S2T_TABLE = {ord(s): ord(t) for t, s in zip(_TRAD_CHARS, _SIMP_CHARS)}


def to_simplified(text: str) -> str:
    """转换为简体中文（优先使用 zhconv，兜底使用内置字符映射表）。"""
    if not text:
        return ''
    if _ZHCONV_AVAILABLE:
        try:
            return zhconv.convert(text, 'zh-cn')
        except Exception:
            pass
    return text.translate(_T2S_TABLE)


def to_traditional(text: str) -> str:
    """转换为繁体中文（优先使用 zhconv，兜底使用内置字符映射表）。"""
    if not text:
        return ''
    if _ZHCONV_AVAILABLE:
        try:
            return zhconv.convert(text, 'zh-tw')
        except Exception:
            pass
    return text.translate(_S2T_TABLE)


def convert_text(text: str, mode: str = 'keep') -> str:
    """
    通用文本转换：
    mode: 'keep'（原样）, 't2s'（转简体）, 's2t'（转繁体）
    """
    if not text or mode == 'keep':
        return text
    if mode == 't2s':
        return to_simplified(text)
    if mode == 's2t':
        return to_traditional(text)
    return text


def _convert_single_content(content: str, mode: str) -> str:
    """
    对单句歌词正文进行转换，严格保护日文假名与韩文字符。
    """
    if not content or mode == 'keep':
        return content

    # 如果整行包含日文假名或韩文，说明这是日韩原声行，坚决不转
    if JAPANESE_KANA_RE.search(content) or KOREAN_HANGUL_RE.search(content):
        return content

    return convert_text(content, mode)


def convert_lrc(lrc_text: str, mode: str = 'keep') -> str:
    """
    对整份 LRC 歌词进行安全简繁转换。
    
    安全保护规则：
    1. 时间戳 [mm:ss.xx] 与 [ti:] 等元标签严格保留，不被破坏；
    2. 单行双语拼接格式（如 "Hello ｜ 你好"）仅转换中文部分；
    3. 日文原声歌词（含假名）与韩文原声歌词完全原封不动，仅转换中文翻译行；
    4. 纯繁体中文歌（如粤语/港台流行曲）全面转换为规范简体或繁体。
    """
    if not lrc_text or mode == 'keep':
        return lrc_text

    result_lines = []
    for raw in lrc_text.splitlines():
        line = raw.strip('\r')
        if not line.strip():
            result_lines.append(line)
            continue

        # 头部元标签 [ti:歌名], [ar:歌手] 等
        header_match = HEADER_TAG_RE.match(line)
        if header_match:
            tag_name, tag_val = header_match.group(1), header_match.group(2)
            converted_val = convert_text(tag_val, mode)
            result_lines.append(f'[{tag_name}:{converted_val}]')
            continue

        # 时间戳行
        m = TIME_RE.match(line)
        if not m:
            # 无时间戳行（纯文本）
            result_lines.append(_convert_single_content(line, mode))
            continue

        timestamp = m.group(1)
        content = m.group(2)

        # 检查是否为单行内联拼合格式（"原句 ｜ 翻译"）
        if ' ｜ ' in content:
            parts = content.split(' ｜ ')
            converted_parts = [_convert_single_content(p, mode) for p in parts]
            result_lines.append(f"{timestamp}{' ｜ '.join(converted_parts)}")
        else:
            converted = _convert_single_content(content, mode)
            result_lines.append(f"{timestamp}{converted}")

    return '\n'.join(result_lines)
